const norm = (s) => String(s).replace(/\(.*?\)/g, '').replace(/\s+/g, '');

// 일반 보관 기간(일). 알 수 없으면 null — 추측해서 채우지 않습니다.
export function shelfDays(name, storage = '냉장') {
  const n = norm(name);
  // 한 글자 키워드(무, 배)는 다른 단어에 섞이기 쉬워 이름이 정확히 같을 때만 맞춥니다.
  const hit = TABLE.find(([k]) => (k.length === 1 ? n === k : n.includes(k)));
  return hit?.[1][storage] ?? null;
}

export function expiryFrom(name, storage = '냉장') {
  const days = shelfDays(name, storage);
  if (days === null) return null;
  const d = new Date();
  d.setDate(d.getDate() + days);
  return { days, expiry: d.toLocaleDateString('sv') };
}
